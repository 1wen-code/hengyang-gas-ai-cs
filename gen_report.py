body('第三，工单系统尚未与燃气公司的真实调度平台对接。当前工单仅存储在Supabase数据库中，通过管理后台人工查看和处理。在实际生产环境中，紧急工单需要实时推送至调度中心或维修人员的移动终端，触发抢修班组出勤。缺乏与真实业务系统的集成限制了工单系统的实用价值。改进方向包括：开发Webhook推送机制，在工单生成时自动调用燃气公司现有的调度系统API；集成短信或企业微信通知，将工单实时推送至指定的维修人员；开发维修人员专用的移动端小程序，支持接单、到场确认和处理反馈的闭环。')
body('第四，知识库检索以关键词匹配为主，语义理解的深度有限。当前基于Jaccard相似度的检索算法本质上是词汇层面的匹配，无法理解词汇之间的语义关系和上下文含义。例如用户问燃气灶需要装电池吗，系统可能因为电池一词在FAQ中频繁出现于燃气表换电池的场景中而返回错误的匹配结果。这种基于词汇重叠的检索方式在语义相等但词汇完全不同的情况下（如把天然气说成煤气）可能完全失效。改进方向包括：引入向量数据库（如Supabase pgvector）和文本嵌入模型，将FAQ问题转换为高维语义向量后进行余弦相似度检索，实现真正的语义理解层面的匹配；同时保留关键词匹配作为精确查询的补充策略，形成向量检索+关键词检索的混合召回方案。')

