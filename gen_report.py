heading('（一）FAQ智能问答功能', 2)
body('FAQ智能问答是本系统最基本也是最核心的功能模块，承担着处理燃气业务咨询类用户请求的主要职责。该功能模块通过RAG（Retrieval-Augmented Generation，检索增强生成）技术，将大语言模型的自然语言理解和生成能力与衡阳燃气官方业务知识库的精确信息相结合，实现了对用户业务问题的准确、高效答复。')
body('FAQ智能问答功能的工作流程分为四个阶段：意图识别阶段、知识库检索阶段、答案生成阶段和结果返回阶段。在意图识别阶段，系统通过detect_faq函数检测用户输入是否包含业务关键词（如开户、缴费、过户、维修等30余个关键词），判断用户意图是否为业务咨询。这一判断完全基于规则匹配，无需调用AI，响应时间小于1毫秒。在知识库检索阶段，系统使用jieba进行中文分词，将用户问题和FAQ问题分别切分为词集后计算Jaccard相似度（交集大小除以并集大小）。检索过程引入同义词扩展机制（19组同义词映射，如漏气可扩展为泄漏、泄露、跑气、漏），提升了模糊表述的召回率。同时引入精确率惩罚（用户查询词中未匹配比例超过40%时降权0.12）、多词重合加分（交集词数达到3个及以上时每多1词加0.08分，达到5个及以上时额外加0.10分）、短查询长答案降权（输入3词以下但匹配8词以上的FAQ时减0.05分）和精确包含加分（查询与FAQ问题互相包含时加0.15分）四项校准权重。最终Jaccard分数经四项权重修正后截断至[0,1]区间。在答案生成阶段，系统执行场景过滤检查（_scene_mismatch），只有当FAQ问题中超过40%的词未在用户问题中出现时才判定为场景不匹配，降级调用AI生成。否则直接返回知识库中FAQ的标准回答原文，不做AI改写，确保信息准确性与官方表述一致。在结果返回阶段，系统将答案文本、匹配到的FAQ问题标题、所属分类和匹配分数等信息封装为JSON响应返回前端。')
body('FAQ智能问答功能对用户的核心价值在于：用户无需掌握专业的燃气业务术语，可以使用口语化甚至方言化的表达方式提问，系统能够自动进行语义理解和知识检索。例如用户输入灶台跟抽风一样这种非标准的方言表述，系统能够通过jieba分词和同义词扩展识别出其中的火焰不稳定、风门异常等核心意图，并返回对应的故障排查建议。对于时间紧迫、需要快速获取准确信息的用户，FAQ直接返回官方标准答案，避免了AI生成可能带来的信息偏差或编造风险。对于知识库无法覆盖的问题，系统降级调用DeepSeek大模型进行推理生成，确保所有用户问题都能得到有意义的回应。')

heading('（二）多轮上下文系统', 2)
body('多轮上下文系统是提升AI客服对话自然度和连贯性的关键功能模块。在真实的客服对话场景中，用户很少通过单条消息完整表达所有需求，而是倾向于通过多轮交互逐步明确问题、追问细节、确认理解。例如在开户咨询的典型场景中，用户的对话路径可能是：首先询问怎么开户，在获取开户流程后追问需要什么材料，再问多少钱，接着问多久能办好，最后确认可以代办吗。每一轮追问都建立在对前一轮回答的理解基础之上，如果系统不具备上下文记忆和追踪能力，每一次追问都将被视为全新的独立问题，导致回答与前后文脱节，用户体验急剧下降。')
body('本系统的多轮上下文机制由session_manager.py和faq_handler.py两个模块协同实现。session_manager.py负责每个用户会话的生命周期管理，维护一个包含以下字段的会话数据结构：mode（当前模式，从normal/danger/human/faq/smalltalk中五选一）、history（对话历史列表，保留最近8轮共16条消息，每条记录包含role和content字段）、last_topic（上一轮话题标签，如开户业务>居民开户）、last_active（最后活跃时间戳，用于过期清理）。每个会话以用户的唯一标识符（session_id，由Flask会话中生成的12位随机hex字符串作为键进行索引，存储在服务端内存字典中，通过threading-safe的方式支持多用户并发访问。faq_handler.py负责在知识库检索阶段利用会话上下文增强搜索效果。当用户发送的消息长度小于或等于10字且当前会话中存在有效的last_topic时，系统判定这很可能是一个短追问（如需要什么材料、多少钱、多久等）。此时，系统调用TOPIC_EXTRACT映射表将last_topic中的完整分类标签（如开户业务>居民开户）提取为核心话题词（如开户），然后将核心话题词与用户消息拼接为增强后的搜索查询字符串（如开户 需要什么材料），用于知识库检索。这一机制显著提升了短追问场景下的FAQ匹配准确率。')
body('系统还内置了话题保持与切换的智能判断逻辑，通过消息长度阈值（4字）来区分新话题和追问：长度超过4字的消息被认为是新话题的开启，系统将更新last_topic为当前FAQ匹配结果所属的分类标签；长度在4字及以下的消息被认为是追问，系统保留原last_topic不变，确保多轮对话的上下文连续性不被单条短消息意外中断。此外，系统在每次新对话开始时（客户端传入空的history列表）自动调用sessions.reset()将会话重置为初始状态，避免前后两次独立对话之间的上下文交叉污染。同时内置了1小时过期自动清理机制，每5分钟扫描一次所有会话，将last_active时间超过3600秒的会话从内存中移除，防止长时间运行导致的内存泄漏。')
body('多轮上下文能力对用户的直接价值在于显著降低了用户与AI客服之间的沟通成本。传统AI客服要求用户每次提问都完整表述问题背景（如我要办开户，需要什么材料），而本系统能够自动继承前文语境，用户只需要说需要什么材料即可获得准确回答。这种自然流畅的多轮交互体验与传统人工客服的对话模式高度接近，大幅降低了用户的认知负担和输入成本，特别有利于不擅长精确表达的技术弱势群体（如老年用户）。对于燃气公司而言，高效的多轮上下文理解意味着单次服务会话的平均交互轮次减少、用户问题解决率提升、客服资源利用效率提高。')

