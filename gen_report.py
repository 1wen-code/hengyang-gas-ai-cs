body('Router路由分流机制是本系统架构设计的核心创新点，其设计理念与传统的单一大模型对话模式有本质区别。在传统AI客服架构中，用户的每一次输入都被统一发送至大模型进行处理，大模型需要同时承担意图识别、风险评估、知识检索和答案生成等多项职责。这种All-in-one模式存在三个固有缺陷：一是大模型的推理延迟不确定性导致危险场景下无法保证即时响应；二是大模型在多任务场景下可能产生回复风格的不一致甚至人格分裂；三是每次调用均消耗API Token，导致运营成本不可控。')
