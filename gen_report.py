body('第一，大模型响应速度受网络条件影响较大。normal模式下的DeepSeek API调用需要经过国际网络往返，实测响应时间在5-7秒之间，虽然相比人工客服的分钟级等待已有显著改善，但对于习惯了搜索引擎秒级响应的用户而言，5-7秒的等待仍会影响连续的对话体验。特别是在移动网络环境下，网络延迟的波动可能进一步拉长响应时间。改进方向包括：探索使用DeepSeek国内镜像节点或私有化部署方案，减少国际网络延迟；引入流式输出（Streaming）机制，让用户看到逐字生成的回复过程，降低心理等待感知；研究使用更轻量的小模型（如DeepSeek-lite或本地量化模型）替代完整版deepseek-chat处理知识库已覆盖的简单问题，以推理速度换取计算资源。')
