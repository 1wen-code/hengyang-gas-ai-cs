heading('（二）RAG知识库检索算法', 2)
body('RAG（检索增强生成）知识库检索算法是本系统实现FAQ智能问答的技术基础。算法通过将用户查询与预先构建的结构化FAQ知识库进行相似度匹配，检索出最相关的标准问答对，为答案生成提供精确的信息支撑。本系统采用的RAG方案在算法层面做了多项针对中文客服场景的定制优化，具体包括以下四个核心技术环节。')
body('第一环节为中文分词与同义词扩展。系统使用jieba分词器对用户查询文本和知识库中每条FAQ问题进行分词处理，得到各自的词集。jieba内置了超过34万条词汇的词典，支持精确模式、全模式和搜索引擎模式三种分词策略，本系统使用默认的精确模式以保证分词的准确性。分词后，系统通过SYNONYM_MAP（19组同义词映射）对用户查询词集进行扩展。例如，当用户查询中包含漏气时，系统自动扩展为[泄漏, 泄露, 跑气, 漏]；当查询中包含缴费时，扩展为[充值, 交费, 支付, 付款, 交钱]。这种同义词扩展机制有效解决了不同用户使用不同措辞表达同一概念导致的检索召回率低的问题。')
body('第二环节为Jaccard相似度计算与权重校准。Jaccard相似度定义为两个词集交集大小除以并集大小，值域为[0, 1]，值越大表示两个文本的词汇重叠度越高。为克服单纯Jaccard相似度在短查询场景下容易被长文本偶然词汇重叠刷高分的缺陷，系统引入了四项校准权重。精确率惩罚：当用户查询词中有超过40%的词未在FAQ问题中出现时，相似度分数降低0.12，用于抑制用户说了很多无关词但FAQ恰好包含了其中几个关键词导致的虚高分数。多词重合加分：当用户查询与FAQ问题的词集交集达到3个词以上时，每多一个词加0.08分（即交集3词加0.08，4词加0.16，依此类推）；当交集达到5个词以上时，额外再加0.10分。这一加权使得真正相关的长文本匹配获得更高的分数优势。短查询长答案降权：当用户输入3个词以下而FAQ问题包含8个词以上时，相似度分数降低0.05，用于防止极简查询（如漏了）因为与长篇FAQ偶尔共享一两个关键词而获得过高的匹配分数。精确包含加分：当用户查询文本完整包含FAQ问题文本或反之被包含时，相似度分数增加0.15，用于奖励查询与FAQ之间存在的精确包含关系。经四项权重修正后的最终分数截断至[0, 1]区间。')
body('第三环节为Top-K多路召回。系统对知识库中全部1009条FAQ逐一计算上述校准Jaccard相似度分数，按分数降序排列后取前K条结果。FAQ模式（faq_handler）使用K=3，Normal模式（normal_handler）使用K=2。当最高分FAQ的分数超过MATCH_THRESHOLD（当前设定为0.28）时，该FAQ被认为是有效匹配，其标准答案被直接返回或作为AI生成的参考上下文。当最高分低于阈值时，faq_handler返回None降级信号，由normal_handler调用大模型进行推理生成。')
body('第四环节为场景过滤算法（_scene_mismatch）。该算法是解决FAQ错误匹配问题的关键创新。算法将匹配到的FAQ问题文本和用户原始消息文本分别送入jieba分词，构建两个词集：用户词集U和FAQ词集F。计算F中不在U中的词数（extra = F - U），然后计算extra占F总词数的比例（ratio = len(extra) / len(F)）。当ratio超过0.4（即FAQ问题中超过40%的词在用户消息中完全没有出现）时，系统判定匹配到的FAQ与用户的实际意图存在显著的场景差异。例如，用户输入怎么办理开户，知识库返回的最佳匹配是业主在国外怎么办理开户，后者包含了在国外、业主等用户完全没有提及的场景限定词。F词集为[业主, 在, 国外, 怎么, 办理, 开户]，U词集为[怎么, 办理, 开户]。F中不在U中的词为[业主, 在, 国外]，共3个词，占F总词数（6个）的50%，超过40%阈值，因此触发场景过滤，faq_handler返回None降级到normal_handler，由AI生成通用的开户流程回答而非错误的国外代办回答。')

