def fn(run, cn='宋体', en='Times New Roman', sz=12, bold=False):
    run.font.size = Pt(sz); run.font.bold = bold
    run.font.name = en; run._element.rPr.rFonts.set(qn('w:eastAsia'), cn)

def heading(text, level=1):
    sizes = {1:16, 2:15, 3:14}
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(18)
    p.paragraph_format.space_after = Pt(10)
    p.paragraph_format.line_spacing = 1.5
    r = p.add_run(text); fn(r, '黑体', 'Times New Roman', sizes.get(level,14), bold=True)
    if level == 1: p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p

def body(text, indent=True):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(4)
    if indent: p.paragraph_format.first_line_indent = Pt(24)
    r = p.add_run(text); fn(r, '宋体', 'Times New Roman', 12)
    return p

def bullet(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(1.5)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run(text); fn(r, '宋体', 'Times New Roman', 12)

def img_hint(filepath, caption=''):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(6)
    try:
        doc.add_picture(filepath, width=Cm(14))
        p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p2.add_run(f'图：{caption}'); fn(r, '黑体', 'Times New Roman', 10, bold=True)
    except:
        r = p.add_run(f'[图片缺失：{caption}]'); fn(r, '黑体', 'Times New Roman', 11, bold=True)

def page_break():
    doc.add_page_break()

def tbl(headers, rows):
    t = doc.add_table(rows=1+len(rows), cols=len(headers))
    t.style = 'Table Grid'
    from docx.enum.table import WD_TABLE_ALIGNMENT
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ''
        p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h); fn(r, '黑体', 'Times New Roman', 10, bold=True)
        shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="1a1a2e"/>')
        c._element.get_or_add_tcPr().append(shd)
        r.font.color.rgb = RGBColor(255,255,255)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            c = t.rows[ri+1].cells[ci]; c.text = ''
            p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(str(val)); fn(r, '宋体', 'Times New Roman', 10)
            if ri % 2 == 0:
                shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="f0f0f5"/>')
                c._element.get_or_add_tcPr().append(shd)
    doc.add_paragraph()

def add_toc(text, level=1, page_num=''):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(1)
    p.paragraph_format.line_spacing = 1.8

    # 手动构造圆点引导线
    if level == 1:
        max_chars = 42  # 一级标题最大字符宽度
        prefix = text
        dot_count = max_chars - len(text) * 2  # 中文字宽约2个英文字符
        dots = '.' * max(3, dot_count)
        full_text = f'{prefix} {dots} {page_num}'
        p.paragraph_format.left_indent = Cm(0)
        r = p.add_run(full_text); fn(r, '黑体', 'Times New Roman', 14, bold=True)

    elif level == 2:
        max_chars = 48
        prefix = '    ' + text  # 缩进
        dot_count = max_chars - len(text) * 2 - 4
        dots = '.' * max(3, dot_count)
        full_text = f'{prefix} {dots} {page_num}'
        p.paragraph_format.left_indent = Cm(0.8)
        r = p.add_run(full_text); fn(r, '宋体', 'Times New Roman', 12)

    else:
        max_chars = 52
        prefix = '        ' + text
        dot_count = max_chars - len(text) * 2 - 8
        dots = '.' * max(3, dot_count)
        full_text = f'{prefix} {dots} {page_num}'

